firstNumber = int(input("Enter first number:-"))
secondNumber = int(input("Enter second number:-"))

operation = input("Enter operation:-")

if(operation == "+"):
    print(firstNumber + secondNumber)
elif(operation == "-"):
    print(firstNumber-secondNumber)
elif(operation == "*"):
    print(firstNumber*secondNumber)
elif(operation == "/"):
    print(firstNumber/secondNumber)
else:
    print("betichod sahi chiz daal")
